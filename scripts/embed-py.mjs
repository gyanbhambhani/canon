// Embed packages/compiler/py/*.py into packages/compiler/src/pyruntime.ts, so the compiler (which
// has no dependencies and runs in the browser) can write them. A test keeps the two in sync.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "packages", "compiler", "py");
const files = readdirSync(dir).filter((f) => f.endsWith(".py")).sort();
const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))},`);
const out = `// Generated by scripts/embed-py.mjs from packages/compiler/py: edit those files, then run pnpm embed-py.
/** The fixed Python files of the FastAPI backend, by file name. */
export const PY_RUNTIME: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
writeFileSync(join(import.meta.dirname, "..", "packages", "compiler", "src", "pyruntime.ts"), out);
console.log(`embedded ${files.join(", ")}`);
