"""
Summarize results/*.json into REPORT.md and likelihood.svg (and copy the chart to the docs).

For each construct and model: the mean over contexts of the log-likelihood difference
(nats) between Canon's current spelling and the best alternative. Positive means the model
prefers what Canon already requires. Also reported: the probability ratio e^delta, and how many
of the three contexts agree on the winner.
"""
import json
import math
import shutil
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).parent
ROOT = HERE.parent.parent


def summarize(result):
    rows = []
    for c in result["constructs"]:
        variants = sorted({r["variant"] for r in c["rows"]})
        contexts = sorted({r["context"] for r in c["rows"]})
        lp = {(r["context"], r["variant"]): r["logprob"] for r in c["rows"]}
        mean = {v: sum(lp[(ci, v)] for ci in contexts) / len(contexts) for v in variants}
        winner = max(variants, key=lambda v: mean[v])
        alts = [v for v in variants if v != c["canon"]]
        best_alt = max(alts, key=lambda v: mean[v])
        delta = mean[c["canon"]] - mean[best_alt]
        agree = sum(1 for ci in contexts if max(variants, key=lambda v: lp[(ci, v)]) == winner)
        rows.append(dict(id=c["id"], question=c["question"], canon=c["canon"], alternatives=alts, delta=delta,
                         ratio=math.exp(delta), agree=agree, contexts=len(contexts), winner=winner))
    return rows


def main():
    results = [json.loads(p.read_text()) for p in sorted((HERE / "results").glob("*.json"))]
    if not results:
        raise SystemExit("no results yet: run score.py first")
    tables = {r["model"]: summarize(r) for r in results}
    models = list(tables)
    ids = [row["id"] for row in tables[models[0]]]

    lines = [
        "# Likelihood study: which spelling do models find most natural?",
        "",
        "Generated by `research/likelihood/report.py` from `results/*.json`. Method: each construct is written",
        "several equivalent ways inside three small programs; each program is scored by its total",
        "log-probability under a local open-weights base model (the same one-line header precedes every",
        "program). Delta is Canon's current spelling minus the best alternative, in nats, averaged over",
        "contexts: positive means the model prefers what Canon already requires. Ratio is e^delta.",
        "",
    ]
    for m in models:
        lines += [f"## {m}", "", "| Construct | Canon spelling | Alternative | Winner | Delta (nats) | Ratio | Contexts agreeing |",
                  "| --- | --- | --- | --- | ---: | ---: | :---: |"]
        for row in tables[m]:
            lines.append(
                f"| {row['question'].replace('|', '\\|')} | {row['canon']} | {', '.join(row['alternatives'])} | **{row['winner']}** | "
                f"{row['delta']:+.2f} | {row['ratio']:.3g}x | {row['agree']}/{row['contexts']} |"
            )
        lines.append("")
    (HERE / "REPORT.md").write_text("\n".join(lines))

    fig, ax = plt.subplots(figsize=(8, 0.42 * len(ids) + 1.2))
    h = 0.8 / len(models)
    colors = ["#2563eb", "#9333ea", "#0891b2"]
    for mi, m in enumerate(models):
        vals = [next(r["delta"] for r in tables[m] if r["id"] == i) for i in ids]
        ys = [y + (mi - (len(models) - 1) / 2) * h for y in range(len(ids))]
        ax.barh(ys, vals, height=h, color=colors[mi % len(colors)], label=m.split("/")[-1])
    ax.axvline(0, color="#444", linewidth=0.8)
    ax.set_yticks(range(len(ids)), ids)
    ax.invert_yaxis()
    ax.set_xlabel("log-likelihood of Canon's spelling minus best alternative (nats)  →  Canon's choice preferred")
    ax.legend(loc="lower right", fontsize=8, frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    svg = HERE / "likelihood.svg"
    fig.savefig(svg)
    public = ROOT / "apps" / "web" / "public" / "research"
    public.mkdir(parents=True, exist_ok=True)
    shutil.copy(svg, public / "likelihood.svg")
    print((HERE / "REPORT.md").read_text())


if __name__ == "__main__":
    main()
