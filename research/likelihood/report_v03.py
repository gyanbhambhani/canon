"""
Summarize results-v0.3/*.json into REPORT-v0.3.md (same table format as REPORT.md, no chart).

For each construct and model: the mean over contexts of the log-likelihood difference (nats)
between the `canon` spelling (v0.2's, or the baseline candidate where v0.2 has none) and the best
alternative. Positive means the model prefers the canon spelling. Also: the ratio e^delta, and
how many of the three contexts agree on the winner.
"""
import json
from pathlib import Path

from report import summarize

HERE = Path(__file__).parent


def main():
    results = [json.loads(p.read_text()) for p in sorted((HERE / "results-v0.3").glob("*.json"))]
    if not results:
        raise SystemExit("no results yet: run score_v03.py first")
    lines = [
        "# Likelihood study, v0.3 candidates",
        "",
        "Generated by `research/likelihood/report_v03.py` from `results-v0.3/*.json`; constructs are in",
        "`constructs_v03.py`. Same method as `REPORT.md`: each construct is written several equivalent ways",
        "inside three small Canon v0.2-style programs, and each program is scored by its total",
        "log-probability under a local open-weights base model (the same one-line header precedes every",
        "program). Delta is the canon spelling minus the best alternative, in nats, averaged over contexts:",
        "positive means the model prefers the canon spelling. Ratio is e^delta. \"Canon\" is v0.2's",
        "spelling, except fn-type-effects, which v0.2 cannot express (there `clause` is just the baseline).",
        "",
        "Totals are not length-normalized: a variant that needs more text (a helper function, an extra",
        "`let`) pays for it, which is intended (it is the likelihood of writing that exact program).",
        "",
    ]
    for r in results:
        lines += [f"## {r['model']}", "",
                  "| Construct | Canon spelling | Alternative | Winner | Delta (nats) | Ratio | Contexts agreeing |",
                  "| --- | --- | --- | --- | ---: | ---: | :---: |"]
        for row in summarize(r):
            lines.append(
                f"| {row['question'].replace('|', '\\|')} | {row['canon']} | {', '.join(row['alternatives'])} | "
                f"**{row['winner']}** | {row['delta']:+.2f} | {row['ratio']:.3g}x | {row['agree']}/{row['contexts']} |"
            )
        lines.append("")
    (HERE / "REPORT-v0.3.md").write_text("\n".join(lines))
    print((HERE / "REPORT-v0.3.md").read_text())


if __name__ == "__main__":
    main()
