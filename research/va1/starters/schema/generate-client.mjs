// The schema-driven chain: Pydantic constraints -> OpenAPI -> TypeScript.
//   node generate-client.mjs
// 1. runs the backend's FastAPI app to get its OpenAPI schema (with $VA1_PYTHON, default python3) and
//    writes frontend/openapi.json;
// 2. generates frontend/src/api/schema.d.ts (types) with openapi-typescript 7.13.0;
// 3. writes frontend/src/api/schemas.json: the schema objects of components.schemas, which
//    frontend/src/api/validate.ts compiles into validators with ajv 8.17.1.
// Every constraint the Pydantic models carry (Field(min_length, max_length, ge, le, gt, lt, pattern,
// multiple_of), Literal, list length) reaches the client this way; rules a schema cannot state do not.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const python = process.env.VA1_PYTHON ?? "python3";
const text = execFileSync(python, ["-c", "import json, main; print(json.dumps(main.app.openapi(), indent=2))"], {
  cwd: join(here, "backend"),
  encoding: "utf8",
});
const schema = JSON.parse(text);
writeFileSync(join(here, "frontend", "openapi.json"), text);
const ast = await openapiTS(schema);
const header = "// Generated by openapi-typescript from frontend/openapi.json: run node generate-client.mjs.\n";
writeFileSync(join(here, "frontend", "src", "api", "schema.d.ts"), header + astToString(ast));
writeFileSync(join(here, "frontend", "src", "api", "schemas.json"), JSON.stringify(schema.components?.schemas ?? {}, null, 2) + "\n");
console.log("generated frontend/src/api/schema.d.ts and schemas.json");
