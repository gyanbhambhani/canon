"""
Summarize results/*.json into REPORT.md.

For each construct and model: the mean over contexts of each variant's log-likelihood; the winner
(highest mean); and the delta between the design's spelling (`chosen` in constructs_v04.py, as
finally ruled) and the best other spelling, in nats. Positive delta means the model prefers the
chosen spelling. Also: the ratio e^delta, and in how many contexts the chosen spelling beats every
alternative.
"""
import json
import math
from pathlib import Path

from constructs_v04 import CONSTRUCTS

CHOSEN = {c["id"]: c["chosen"] for c in CONSTRUCTS}

HERE = Path(__file__).parent


def summarize(result: dict) -> list[dict]:
    rows = []
    for c in result["constructs"]:
        ctxs = sorted({r["context"] for r in c["rows"]})
        names = list(dict.fromkeys(r["variant"] for r in c["rows"]))
        lp = {(r["context"], r["variant"]): r["logprob"] for r in c["rows"]}
        mean = {n: sum(lp[(i, n)] for i in ctxs) / len(ctxs) for n in names}
        chosen = CHOSEN[c["id"]]
        others = [n for n in names if n != chosen]
        best_other = max(others, key=lambda n: mean[n])
        delta = mean[chosen] - mean[best_other]
        agree = sum(1 for i in ctxs if all(lp[(i, chosen)] > lp[(i, o)] for o in others))
        rows.append({
            "id": c["id"], "question": c["question"], "chosen": chosen, "alternatives": others,
            "winner": max(names, key=lambda n: mean[n]), "delta": delta, "ratio": math.exp(delta),
            "agree": agree, "contexts": len(ctxs), "means": mean,
        })
    return rows


def main():
    results = [json.loads(p.read_text()) for p in sorted((HERE / "results").glob("*.json"))]
    if not results:
        raise SystemExit("no results yet: run score_v04.py first")
    lines = [
        "# Likelihood study, v0.4 (Python-shaped contexts)",
        "",
        "Generated by `research/v0.4/likelihood/report_v04.py` from `results/*.json`; the constructs are in",
        "`constructs_v04.py`. Each construct is written in equivalent spellings inside three small programs written in",
        "the candidate v0.4 surface (def, indentation, Python type names, decorators). Each program is scored by its",
        "total log-probability under a local base model, after the header",
        f"`{results[0]['header'].strip()}`.",
        "",
        "**Chosen** is the v0.4 spelling (docs/v0.4-design.md has each ruling). **Delta** is the chosen spelling's mean",
        "log-likelihood minus the best alternative's, in nats over the three contexts: positive means the model",
        "prefers the chosen spelling, and negative means v0.4 chose against the model (the design doc says why).",
        "Ratio is e^delta. Totals are not length-normalized: a longer spelling pays for its extra tokens.",
        "",
    ]
    for r in results:
        lines += [f"## {r['model']}", "",
                  "| Construct | Chosen | Alternatives | Winner | Delta (nats) | Ratio | Contexts chosen wins |",
                  "| --- | --- | --- | --- | ---: | ---: | :---: |"]
        for row in summarize(r):
            q = row["question"].replace("|", "\\|")
            lines.append(f"| {q} | {row['chosen']} | {', '.join(row['alternatives'])} | **{row['winner']}** | "
                         f"{row['delta']:+.2f} | {row['ratio']:.3g}x | {row['agree']}/{row['contexts']} |")
        lines.append("")
    (HERE / "REPORT.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
