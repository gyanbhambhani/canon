// Regenerate the frontend's API types from the backend's OpenAPI schema:
//   node generate-client.mjs
// Runs the backend's FastAPI app to get its schema (with $SHOP_PYTHON, default python3), writes
// frontend/openapi.json, and turns it into frontend/src/api/schema.d.ts with openapi-typescript.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const python = process.env.SHOP_PYTHON ?? "python3";
const schema = execFileSync(python, ["-c", "import json, main; print(json.dumps(main.app.openapi(), indent=2))"], {
  cwd: join(here, "backend"),
  encoding: "utf8",
});
writeFileSync(join(here, "frontend", "openapi.json"), schema);
const ast = await openapiTS(JSON.parse(schema));
const header = "// Generated by openapi-typescript from frontend/openapi.json: run node generate-client.mjs.\n";
writeFileSync(join(here, "frontend", "src", "api", "schema.d.ts"), header + astToString(ast));
console.log("generated frontend/src/api/schema.d.ts");
