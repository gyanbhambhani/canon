/**
 * v0.5: `canon build` for a project: every file the backend and frontend targets write, with
 * paths relative to the project root, and the drift check (G001) on files already on disk.
 */
import type { CanonConfig } from "./config.js";
import { diag, type Diagnostic } from "./diagnostics.js";
import { inspectGenerated } from "./generated.js";
import type { ProjectResult } from "./project.js";
import { generateFastapi } from "./pygen.js";
import { generateTsClient } from "./tsgen.js";

export interface BuildOutput {
  /** Relative to the project root, with forward slashes. */
  path: string;
  text: string;
  /** Written only if missing (main.py). */
  userOwned: boolean;
  /** The output folder it belongs to (backend or frontend out). */
  dir: string;
}

export type BuildTarget = "fastapi" | "ts-client";

const join = (dir: string, rel: string) => {
  const parts = [...dir.split("/"), ...rel.split("/")].filter((p) => p !== "" && p !== ".");
  const out: string[] = [];
  for (const p of parts) {
    if (p === "..") out.pop();
    else out.push(p);
  }
  return out.join("/");
};

/** Every file the configured targets write. `project` must check clean; throws TargetError (G002). */
export function buildOutputs(project: ProjectResult, config: CanonConfig, only?: BuildTarget, opts: { py?: boolean } = {}): BuildOutput[] {
  const out: BuildOutput[] = [];
  if (config.backend && (!only || only === "fastapi")) {
    const dir = config.backend.out;
    for (const f of generateFastapi(project, opts)) out.push({ path: join(dir, f.path), text: f.text, userOwned: !!f.userOwned, dir });
  }
  if (config.frontend && (!only || only === "ts-client")) {
    const dir = config.frontend.out;
    for (const f of generateTsClient(project)) out.push({ path: join(dir, f.path), text: f.text, userOwned: !!f.userOwned, dir });
  }
  return out;
}

/** The Canon source a generated file names in its header, if any. */
export function generatedFrom(text: string): string | null {
  const m = /^(?:#|\/\/) Generated by Canon \S+ from (.+?)\. Do not edit/.exec(text);
  return m ? m[1] : null;
}

/**
 * G001: a generated file whose contents no longer match its hash was edited by hand. `files` are
 * the files found in the output folders (root-relative path and text).
 */
export function driftDiagnostics(files: { path: string; text: string }[]): { path: string; diagnostic: Diagnostic }[] {
  const out: { path: string; diagnostic: Diagnostic }[] = [];
  for (const f of files) {
    const info = inspectGenerated(f.text);
    if (!info.generated || info.intact) continue;
    const from = generatedFrom(f.text);
    out.push({
      path: f.path,
      diagnostic: diag("G001",
        `${f.path} was edited by hand, but it is generated${from ? ` from ${from}` : ""}: make the change in the Canon source and run canon build (canon build --force discards the edit)`,
        1, 1, { data: { source: from } }),
    });
  }
  return out;
}
